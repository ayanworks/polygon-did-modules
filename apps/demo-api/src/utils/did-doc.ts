import { computeAddress, encodeBase58, SigningKey, toUtf8Bytes } from 'ethers'

export type DidDocument = Record<string, unknown>

export type KeyDetails = {
  address: string
  privateKey: string
  publicKeyBase58: string
}

export type DidDetails = KeyDetails & {
  did: string
}

export const NETWORK_TYPES = ['testnet', 'mainnet'] as const

export type NetworkType = (typeof NETWORK_TYPES)[number]

export const assertNetworkType = (networkType: string): NetworkType => {
  if (networkType !== 'testnet' && networkType !== 'mainnet') {
    throw new Error('Invalid network provided')
  }
  return networkType
}

export const normalizePrivateKey = (privateKey: string): string =>
  privateKey.startsWith('0x') ? privateKey : `0x${privateKey}`

/**
 * Derives address and base58 public key from a private key, mirroring the key
 * derivation performed by `PolygonDID.createKeyPair` so that keys generated by
 * the library and keys supplied by the caller produce equivalent documents.
 */
export const deriveKeyDetails = (privateKey: string): KeyDetails => {
  const key = normalizePrivateKey(privateKey)
  const address = computeAddress(key)
  const publicKeyBase58 = encodeBase58(toUtf8Bytes(SigningKey.computePublicKey(key, true)))
  return { address, privateKey: key, publicKeyBase58 }
}

export const didFromAddress = (address: string, networkType: NetworkType): string =>
  networkType === 'mainnet' ? `did:polygon:${address}` : `did:polygon:${networkType}:${address}`

export const deriveDidDetails = (networkType: string, privateKey: string): DidDetails => {
  const network = assertNetworkType(networkType)
  const keyDetails = deriveKeyDetails(privateKey)
  return { ...keyDetails, did: didFromAddress(keyDetails.address, network) }
}

/**
 * Builds the DID document registered on chain for a given DID and public key.
 */
export const buildDidDocument = (did: string, publicKeyBase58: string): DidDocument => {
  const verificationMethod = {
    id: `${did}#key-1`,
    type: 'EcdsaSecp256k1VerificationKey2019',
    controller: did,
    publicKeyBase58,
  }

  return {
    '@context': ['https://w3id.org/did/v1', 'https://w3id.org/security/suites/secp256k1-2019/v1'],
    id: did,
    verificationMethod: [verificationMethod],
    authentication: [verificationMethod.id],
    assertionMethod: [verificationMethod.id],
    capabilityDelegation: [verificationMethod.id],
    capabilityInvocation: [verificationMethod.id],
    keyAgreement: [verificationMethod.id],
  }
}
